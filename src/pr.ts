import { mkdtemp, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { runFile } from "./fix/exec.js";
import type { FixResult } from "./fix/upgrade.js";
import type { Finding } from "./types.js";

async function git(projectDir: string, args: string[]): Promise<string> {
  const res = await runFile("git", args, projectDir, 120_000);
  if (!res.ok) throw new Error(`git ${args.join(" ")} failed:\n${res.output}`);
  return res.output.trim();
}

/** Fails early, before any fix runs, if a PR could not be opened afterwards. */
export async function checkPrPrerequisites(projectDir: string): Promise<string> {
  const base = await git(projectDir, ["branch", "--show-current"]).catch(() => "");
  if (!base) throw new Error("--pr needs a git repository with a checked-out branch.");
  const remote = await git(projectDir, ["remote", "get-url", "origin"]).catch(() => "");
  if (!/github\.com/.test(remote)) throw new Error("--pr needs an `origin` remote on GitHub.");
  const auth = await runFile("gh", ["auth", "status"], projectDir, 30_000).catch(() => undefined);
  if (!auth?.ok) throw new Error("--pr needs the GitHub CLI (`gh`) installed and logged in.");
  return base;
}

export async function createBranch(projectDir: string, now = new Date()): Promise<string> {
  const stamp = now.toISOString().replace(/[-:]/g, "").replace("T", "-").slice(0, 15);
  const branch = `autofix-cve/${stamp}`;
  await git(projectDir, ["switch", "-c", branch]);
  return branch;
}

export async function abandonBranch(projectDir: string, base: string, branch: string): Promise<void> {
  await git(projectDir, ["switch", base]);
  await git(projectDir, ["branch", "-D", branch]);
}

export function prTitle(results: FixResult[]): string {
  const fixed = results.filter((r) => r.status === "fixed");
  const count = fixed.reduce((n, r) => n + r.fixedVulns.length, 0);
  const names = fixed.map((r) => r.package);
  const list = names.length <= 3 ? names.join(", ") : `${names.slice(0, 3).join(", ")} and ${names.length - 3} more`;
  return `Fix ${count} known ${count === 1 ? "vulnerability" : "vulnerabilities"} in ${list}`;
}

function change(r: FixResult): string {
  if (r.strategy === "backport") return `${r.from} (backported fix)`;
  return `${r.from} → ${r.to}`;
}

export function prBody(results: FixResult[], remaining: Finding[]): string {
  const fixed = results.filter((r) => r.status === "fixed");
  const other = results.filter((r) => r.status !== "fixed");
  const out: string[] = [];
  out.push("## Summary\n");
  out.push("| Package | Change | Strategy | Vulnerabilities |");
  out.push("|---|---|---|---|");
  for (const r of fixed) out.push(`| \`${r.package}\` | ${change(r)} | ${r.strategy} | ${r.fixedVulns.join("<br>")} |`);

  for (const r of fixed) {
    out.push(`\n## \`${r.package}\`\n`);
    out.push("**Evidence**\n");
    for (const e of r.evidence) out.push(`- ${e}`);
    if (r.explanations.length) {
      out.push("\n**What changed**\n");
      for (const e of r.explanations) out.push(`- ${e}`);
    }
    if (r.reason) out.push(`\n> ${r.reason}`);
    out.push(`\nFiles: ${r.changedFiles.map((f) => `\`${f}\``).join(", ")}`);
  }

  if (other.length) {
    out.push("\n## Not fixed\n");
    for (const r of other) out.push(`- \`${r.package}@${r.from}\` (${r.status}): ${r.reason ?? "no reason recorded"}`);
  }

  const left = remaining.reduce((n, f) => n + f.vulns.length, 0);
  out.push("\n## Rescan\n");
  out.push(
    left
      ? `${left} known vulnerabilities remain in ${remaining.map((f) => `\`${f.dependency.name}\``).join(", ")}.`
      : "No known vulnerabilities remain.",
  );
  out.push("\n---\nGenerated by [Auto-FIX-CVE](https://github.com/KJLavender/Auto-FIX-CVE). Review the diff before merging.");
  return out.join("\n");
}

/** Commits the fixed files, pushes the branch and opens a PR. Returns the PR URL. */
export async function openPr(
  projectDir: string,
  base: string,
  branch: string,
  results: FixResult[],
  remaining: Finding[],
): Promise<string> {
  const fixed = results.filter((r) => r.status === "fixed");
  const files = [...new Set(fixed.flatMap((r) => r.changedFiles))];
  await git(projectDir, ["add", "--", ...files]);
  const title = prTitle(results);
  const details = fixed.map((r) => `- ${r.package} ${change(r)}: ${r.fixedVulns.join(", ")}`).join("\n");
  await git(projectDir, ["commit", "-m", title, "-m", details]);
  await git(projectDir, ["push", "-u", "origin", branch]);

  const bodyFile = path.join(await mkdtemp(path.join(tmpdir(), "autofix-pr-")), "body.md");
  await writeFile(bodyFile, prBody(results, remaining), "utf8");
  const res = await runFile(
    "gh",
    ["pr", "create", "--base", base, "--head", branch, "--title", title, "--body-file", bodyFile],
    projectDir,
    120_000,
  );
  if (!res.ok) throw new Error(`gh pr create failed:\n${res.output}`);
  return res.output.trim().split("\n").pop() ?? "";
}
