import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import type { Edit } from "../fix/edits.js";

export const PATCH_DIR = ".autofix-cve/patches";
export const APPLY_SCRIPT = ".autofix-cve/apply-patches.cjs";
export const POSTINSTALL = `node ${APPLY_SCRIPT}`;

export interface PatchFile {
  package: string;
  version: string;
  /** Install location relative to the project, e.g. `node_modules/marked`. */
  path: string;
  edits: Edit[];
}

/**
 * Zero-dependency postinstall script that re-applies backports after every
 * install. Shipping it in the repo avoids adding a patching tool, and its
 * dependency tree, to the project just to keep a security fix in place.
 */
const SCRIPT = String.raw`#!/usr/bin/env node
// Generated by autofix-cve. Re-applies verified security backports after npm install.
// Each patch is a list of exact search/replace edits for one package version.
"use strict";
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const dir = path.join(__dirname, "patches");
let failed = false;

for (const name of fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".json")) : []) {
  const patch = JSON.parse(fs.readFileSync(path.join(dir, name), "utf8"));
  const pkgDir = path.join(root, patch.path);
  const pkgJson = path.join(pkgDir, "package.json");
  if (!fs.existsSync(pkgJson)) continue;
  const installed = JSON.parse(fs.readFileSync(pkgJson, "utf8")).version;
  if (installed !== patch.version) {
    console.warn("[autofix-cve] " + patch.package + " is " + installed + ", patch is for " + patch.version + "; skipped");
    continue;
  }
  let applied = 0;
  for (const edit of patch.edits) {
    const file = path.join(pkgDir, edit.file);
    let content = fs.readFileSync(file, "utf8");
    let search = edit.search;
    let replace = edit.replace;
    if (!content.includes(search) && content.includes("\r\n")) {
      search = search.replace(/\r?\n/g, "\r\n");
      replace = replace.replace(/\r?\n/g, "\r\n");
    }
    const at = content.indexOf(search);
    const unique = at !== -1 && content.indexOf(search, at + 1) === -1;
    // Already applied: the replacement is present and either the original text is gone
    // or the replacement itself contains it. A deletion is applied once its text is gone.
    if (replace !== "" && content.includes(replace) && (at === -1 || replace.includes(search))) continue;
    if (replace === "" && at === -1) continue;
    if (!unique) {
      console.error("[autofix-cve] cannot apply patch to " + patch.package + "/" + edit.file);
      failed = true;
      continue;
    }
    fs.writeFileSync(file, content.slice(0, at) + replace + content.slice(at + search.length));
    applied++;
  }
  if (applied) console.log("[autofix-cve] patched " + patch.package + "@" + patch.version + " (" + applied + " edits)");
}
process.exit(failed ? 1 : 0);
`;

export function patchFileFor(name: string, version: string): string {
  return `${PATCH_DIR}/${name.replace("/", "+")}@${version}.json`;
}

export async function writePatch(projectDir: string, patch: PatchFile): Promise<string> {
  const rel = patchFileFor(patch.package, patch.version);
  await mkdir(path.join(projectDir, PATCH_DIR), { recursive: true });
  await writeFile(path.join(projectDir, rel), JSON.stringify(patch, null, 2) + "\n", "utf8");
  await writeFile(path.join(projectDir, APPLY_SCRIPT), SCRIPT, "utf8");
  return rel;
}

/** True when every edit of a recorded patch is present in the installed files. */
export async function patchApplied(projectDir: string, patchRel: string): Promise<boolean> {
  try {
    const patch = JSON.parse(await readFile(path.join(projectDir, patchRel), "utf8")) as PatchFile;
    for (const e of patch.edits) {
      const content = (await readFile(path.join(projectDir, patch.path, e.file), "utf8")).replace(/\r\n/g, "\n");
      const search = e.search.replace(/\r\n/g, "\n");
      const replace = e.replace.replace(/\r\n/g, "\n");
      const ok = replace === "" ? !content.includes(search) : content.includes(replace);
      if (!ok) return false;
    }
    return true;
  } catch {
    return false;
  }
}

/** Adds the apply script to `postinstall`, keeping any existing postinstall command. */
export async function ensurePostinstall(projectDir: string): Promise<void> {
  const file = path.join(projectDir, "package.json");
  const text = await readFile(file, "utf8");
  const pkg = JSON.parse(text) as { scripts?: Record<string, string> };
  const current = pkg.scripts?.postinstall;
  if (current?.includes(APPLY_SCRIPT)) return;
  pkg.scripts = { ...pkg.scripts, postinstall: current ? `${current} && ${POSTINSTALL}` : POSTINSTALL };
  const indent = text.match(/^[ \t]+(?=")/m)?.[0] ?? 2;
  await writeFile(file, JSON.stringify(pkg, null, indent) + "\n", "utf8");
}
